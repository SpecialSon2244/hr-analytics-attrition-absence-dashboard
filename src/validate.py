"""Data quality checks on the star schema -> docs/validation.md.

Each check is (area, label, SQL returning one number, expected value or None).
Expected None means the value is reported for information only.
Exits non-zero if any check with an expected value fails.
"""
import pathlib
import sys

import duckdb

ROOT = pathlib.Path(__file__).resolve().parents[1]
OUT = ROOT / "docs" / "validation.md"

CHECKS = [
    ("IBM", "Employees (rows)", "SELECT count(*) FROM dim_employee", 1470),
    ("IBM", "Unique employee numbers", "SELECT count(DISTINCT employee_key) FROM dim_employee", 1470),
    ("IBM", "Leavers (Attrition = Yes)", "SELECT sum(is_leaver) FROM fact_attrition_snapshot", 237),
    ("IBM", "Employees without a department",
     "SELECT count(*) FROM dim_employee e ANTI JOIN dim_department d USING (department_key)", 0),
    ("IBM", "Null cells in dim_employee",
     "SELECT sum(" + "+".join("(CASE WHEN {c} IS NULL THEN 1 ELSE 0 END)".format(c=c) for c in [
         "employee_key", "department_key", "job_role", "job_level", "age", "gender", "overtime",
         "monthly_income", "years_at_company", "total_working_years", "years_in_current_role"]) +
     ") FROM dim_employee", 0),
    ("IBM", "Years at company > total working years",
     "SELECT count(*) FROM dim_employee WHERE years_at_company > total_working_years", 0),
    ("IBM", "Years in current role > years at company",
     "SELECT count(*) FROM dim_employee WHERE years_in_current_role > years_at_company", 0),
    ("UCI", "Absence records (rows)", "SELECT count(*) FROM fact_absence", 740),
    ("UCI", "Distinct employees", "SELECT count(DISTINCT absence_employee_key) FROM fact_absence", 36),
    ("UCI", "Records with an unknown reason code",
     "SELECT count(*) FROM fact_absence ANTI JOIN dim_absence_reason USING (reason_code)", 0),
    ("UCI", "Records with reason 0 (no reason recorded)",
     "SELECT count(*) FROM fact_absence WHERE reason_code = 0", None),
    ("UCI", "Records with 0 hours", "SELECT count(*) FROM fact_absence WHERE absence_hours = 0", None),
    ("UCI", "Records with month 0 (not recorded)",
     "SELECT count(*) FROM fact_absence WHERE month_number = 0", None),
    ("UCI", "Disciplinary-failure records that have hours",
     "SELECT count(*) FROM fact_absence WHERE disciplinary_failure = 1 AND absence_hours > 0", 0),
    ("UCI", "Records where UCI season code disagrees with the month",
     "SELECT count(*) FROM fact_absence WHERE month_number > 0 AND season_uci_code_label <> split_part(season_by_month, ' ', 1)", None),
    ("UCI", "Max hours in one record", "SELECT max(absence_hours) FROM fact_absence", None),
    ("SIMULATED", "Requisitions", "SELECT count(*) FROM fact_requisition", 300),
    ("SIMULATED", "Filled requisitions without a hired candidate",
     "SELECT count(*) FROM fact_requisition WHERE status = 'Filled' AND hired_candidate_id IS NULL", 0),
    ("SIMULATED", "Hires per filled requisition > 1",
     "SELECT count(*) FROM (SELECT requisition_id FROM fact_candidate WHERE offer_outcome = 'Accepted' "
     "GROUP BY 1 HAVING count(*) > 1)", 0),
    ("SIMULATED", "Stage dates out of order",
     "SELECT count(*) FROM fact_candidate WHERE screened_date < applied_date OR interview_date < screened_date "
     "OR final_interview_date < interview_date OR offer_date < final_interview_date "
     "OR offer_decision_date < offer_date", 0),
    ("SIMULATED", "Events after the 30 Sep 2026 snapshot",
     "SELECT count(*) FROM fact_candidate_stage WHERE stage_date > DATE '2026-09-30'", 0),
    ("SIMULATED", "Requisition job roles that do not exist at IBM",
     "SELECT count(*) FROM fact_requisition r ANTI JOIN dim_job_role j USING (job_role_key)", 0),
    ("SIMULATED", "Negative time to hire",
     "SELECT count(*) FROM fact_requisition WHERE time_to_hire_days < 0 OR time_to_fill_days < 0", 0),
]

NOTES = """
Notes:

- UCI reason 0 rows are records with no absence reason and, in this file, 0 hours. Most are disciplinary-failure records. They are kept (they are part of the file) and shown as 'No reason recorded'.
- UCI's own season code does not match the calendar months for many rows, so charts use a season derived from the month (Southern Hemisphere).
- The UCI file has no year column, so absence cannot be placed on a calendar timeline.
"""


def main() -> int:
    con = duckdb.connect(str(ROOT / "data" / "hr.duckdb"), read_only=True)
    lines = ["# Validation (generated by src/validate.py, do not edit)", "",
             "| Area | Check | Value | Expected | Result |", "|---|---|---|---|---|"]
    fails = 0
    for area, label, sql, expected in CHECKS:
        value = con.execute(sql).fetchone()[0]
        value = 0 if value is None else int(value)
        if expected is None:
            result = "info"
        elif value == expected:
            result = "pass"
        else:
            result = "FAIL"
            fails += 1
        lines.append(f"| {area} | {label} | {value} | {'-' if expected is None else expected} | {result} |")
        print(f"{result:5} {area:9} {label}: {value}")
    OUT.write_text("\n".join(lines) + "\n" + NOTES)
    print(f"{len(CHECKS)} checks, {fails} failed -> {OUT.relative_to(ROOT)}")
    return 1 if fails else 0


if __name__ == "__main__":
    sys.exit(main())

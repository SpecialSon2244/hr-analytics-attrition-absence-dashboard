"""Write docs/findings.md from docs/findings.json. Every number in the text is read
from the query results, nothing is typed in by hand."""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parents[1]
F = json.loads((ROOT / "docs" / "findings.json").read_text())


def by(key, col):
    return {str(r[col]).split(". ", 1)[-1]: r for r in F[key]}


def n(v, d=0):
    return f"{v:,.{d}f}"


def main() -> None:
    w = F["f1_workforce_overall"][0]
    dept = by("f2_by_department", "department")
    ot = by("f3_by_overtime", "overtime")
    role = F["f4_by_job_role"]
    ten = by("f5_by_tenure_band", "tenure_band")
    inc = by("f6_by_income_band", "income_band")
    trv = by("f7_by_travel", "business_travel")
    age = by("f8_by_age_band", "age_band")
    sat = by("f9_by_job_satisfaction", "job_satisfaction")
    oti = {(r["overtime"], r["income_band"].split(". ", 1)[1]): r for r in F["f10_overtime_x_income"]}
    lvl = by("f11_by_job_level", "job_level")
    a = F["f20_absence_overall"][0]
    rs = F["f21_absence_by_reason"]
    wd = by("f22_absence_by_weekday", "weekday_name")
    se = F["f23_absence_by_season"]
    br = F["f25_bradford"][0]
    dis = {r["disciplinary_failure"]: r for r in F["f26_disciplinary"]}
    h = F["f30_hiring_overall_SIMULATED"][0]
    fun = by("f31_funnel_SIMULATED", "stage")
    src = F["f32_by_source_SIMULATED"]
    hd = F["f33_by_department_SIMULATED"]
    top2 = rs[0]["hours"] + rs[1]["hours"]
    nonicd = sum(r["hours"] for r in rs if r["reason_group"] == "Non-ICD")
    consult = next(r for r in rs if r["reason_name"] == "Medical consultation")
    low_ot = oti[("Yes", "Under 3k")]
    hi_no = oti[("No", "10k+")]
    t = f"""# Findings

Generated by `src/report.py` from `docs/findings.json` (the output of the named queries in
`sql/findings.sql`). Full result tables: [findings_results.md](findings_results.md).

Three separate subject areas, three separate organisations. They are never joined:

| Area | Source | Real or not |
|---|---|---|
| Headcount and attrition | IBM HR Analytics Employee Attrition & Performance | **Fictional** dataset created by IBM data scientists |
| Absence | UCI Absenteeism at work (id 445) | Real records, courier company in Brazil, Jul 2007 to Jul 2010 |
| Time to hire | `data/simulated/SIMULATED_*.csv` | **SIMULATED** by `src/simulate_hiring.py` |

## 1. Headcount and attrition (IBM, fictional)

**1.1 One in six employees left.** {n(w['employees'])} employees in the snapshot, {n(w['leavers'])} with
Attrition = Yes: an attrition rate of **{w['attrition_pct']}%**. {n(w['active'])} are still active.
The dataset is one undated snapshot, so this is a rate for the period the snapshot covers,
not an annual rate. *(f1_workforce_overall)*

**1.2 Sales loses the most people.** Sales {dept['Sales']['attrition_pct']}% ({dept['Sales']['leavers']} of
{dept['Sales']['employees']}), Human Resources {dept['Human Resources']['attrition_pct']}%, Research & Development
{dept['Research & Development']['attrition_pct']}%. By role, **{role[0]['job_role']}s** leave at
**{role[0]['attrition_pct']}%** ({role[0]['leavers']} of {role[0]['employees']}), followed by {role[1]['job_role']}s
({role[1]['attrition_pct']}%) and {role[2]['job_role']} staff ({role[2]['attrition_pct']}%). {role[-1]['job_role']}s
have the lowest rate ({role[-1]['attrition_pct']}%). *(f2_by_department, f4_by_job_role)*

**1.3 Overtime is the clearest single split.** Employees who work overtime left at
**{ot['Yes']['attrition_pct']}%**, against {ot['No']['attrition_pct']}% for those who do not
({ot['Yes']['leavers']} of {n(ot['Yes']['employees'])} vs {ot['No']['leavers']} of {n(ot['No']['employees'])}). *(f3_by_overtime)*

**1.4 Low pay plus overtime is the riskiest group.** Overtime workers earning under 3k a month left
at **{low_ot['attrition_pct']}%** ({low_ot['leavers']} of {low_ot['employees']}). Employees with no overtime and
10k+ a month left at {hi_no['attrition_pct']}%. Overtime raises attrition in every income band.
The dataset gives no currency for monthly income. *(f10_overtime_x_income)*

**1.5 The first two years are the riskiest.** {ten['0-2 yrs']['attrition_pct']}% of employees with 0 to 2 years
at the company left, against {ten['11+ yrs']['attrition_pct']}% at 11+ years. Leavers had an average tenure of
{w['avg_tenure_leavers']} years, active employees {w['avg_tenure_active']}. By age: {age['18-24']['attrition_pct']}%
of 18 to 24 year olds left, {age['35-44']['attrition_pct']}% of 35 to 44 year olds. By job level: level 1
{lvl['1']['attrition_pct']}%, level 2 {lvl['2']['attrition_pct']}%. *(f5_by_tenure_band, f8_by_age_band,
f11_by_job_level)*

**1.6 Pay, travel and satisfaction.** Attrition is {inc['Under 3k']['attrition_pct']}% under 3k a month and
{inc['10k+']['attrition_pct']}% at 10k+. Frequent travellers: {trv['Travels frequently']['attrition_pct']}% vs
{trv['No travel']['attrition_pct']}% for non-travellers. Low job satisfaction: {sat['Low']['attrition_pct']}% vs
{sat['Very high']['attrition_pct']}% at very high. The median monthly income of leavers is
{n(w['median_income_leavers'])}, of active employees {n(w['median_income_active'])}. *(f6, f7, f9, f1)*

These are descriptive splits of a fictional dataset. Tenure, age, job level and income move
together, so the splits overlap and do not show cause.

## 2. Absence (UCI, real records, different company)

**2.1 Total absence.** {a['records']} absence records for {a['employees']} employees, **{n(a['total_hours'])}
hours** in total. That is {a['hours_per_employee']} hours per employee over the roughly three years
(about **{a['hours_per_employee_per_year']} hours per employee per year**). The average absence lasts
{a['avg_hours_per_spell']} hours, the median {a['median_hours_per_spell']:.0f} hours: most absences are short,
a few are long. *(f20_absence_overall)*

**2.2 Musculoskeletal problems and injuries cost the most hours.** {rs[0]['reason_name']}
({rs[0]['pct_of_hours']}% of hours) and {rs[1]['reason_name'].lower()} ({rs[1]['pct_of_hours']}%) together account for
**{100 * top2 / a['total_hours']:.1f}%** of all absence hours. The most frequent reason, medical consultation
({consult['records']} records), is short: {consult['avg_hours']} hours on average. Non-ICD reasons (consultations,
follow-ups, physiotherapy, unjustified absence and so on) are {100 * nonicd / a['total_hours']:.1f}% of hours.
*(f21_absence_by_reason)*

**2.3 Mondays are the worst day.** Monday has **{wd['Mon']['pct_of_hours']}%** of absence hours
({n(wd['Mon']['hours'])} h), Thursday {wd['Thu']['pct_of_hours']}% ({n(wd['Thu']['hours'])} h). Monday
absences are also longer: {wd['Mon']['avg_hours']} hours on average vs {wd['Thu']['avg_hours']} on Thursday.
*(f22_absence_by_weekday)*

**2.4 Season.** {se[0]['season_by_month']} has the most hours ({se[0]['pct_of_hours']}%), {se[-1]['season_by_month']}
the fewest ({se[-1]['pct_of_hours']}%). Seasons are derived from the month (Southern Hemisphere), because
UCI's season code does not match the months in the file. *(f23_absence_by_season)*

**2.5 A few people account for much of the absence.** The 5 employees with the most hours have
**{br['top5_share_of_hours_pct']}%** of all hours. {br['employees_bradford_250_plus']} of {br['employees']} employees
have an annualised Bradford factor of 250 or more (median {n(br['median_bradford_annual'])}). The Bradford factor
weights frequent short absences heavily; it is used here as a descriptive measure only.
*(f25_bradford, f25b_bradford_top10)*

**2.6 Data quirk.** The {dis[True]['records']} records flagged as disciplinary failure all have
{dis[True]['hours']} absence hours, and most have reason code 0. They are kept but add no hours.
*(f26_disciplinary)*

## 3. Time to hire (SIMULATED)

Everything in this section comes from a **SIMULATED** pipeline. The numbers mostly reflect the
assumptions in `src/simulate_hiring.py` (pass rates, delays, acceptance rates). They show how
the metrics are built, not how any real company hires.

**3.1 Volume.** {h['requisitions']} requisitions opened Jan 2025 to Jun 2026, weighted by where IBM's leavers
were. On the 30 Sep 2026 snapshot {h['filled']} are filled, {h['open']} open, {h['cancelled']} cancelled.
{n(h['applicants'])} applicants. *(f30_hiring_overall_SIMULATED)*

**3.2 Speed.** Median **time to hire {h['median_time_to_hire_days']:.0f} days** (hired candidate's application to
offer acceptance; average {h['avg_time_to_hire_days']}). Median **time to fill {h['median_time_to_fill_days']:.0f} days**
(requisition opened to offer acceptance; average {h['avg_time_to_fill_days']}). The departments are within about a
day of each other ({', '.join(f"{r['department']} {r['median_time_to_hire_days']:g}" for r in hd)} days median time
to hire), as expected because the simulation uses the same delays for every department.
*(f33_by_department_SIMULATED)*

**3.3 Funnel.** {fun['Screened']['pct_of_applicants']}% of applicants pass screening,
{fun['Interview']['pct_of_applicants']}% reach a first interview, {fun['Offer']['pct_of_applicants']}% get an offer and
{fun['Hired']['pct_of_applicants']}% are hired. **Offer acceptance: {h['offer_accept_pct']}%.**
*(f31_funnel_SIMULATED)*

**3.4 Source.** {src[0]['source']} gives the most hires per 100 applicants ({src[0]['hire_per_100_applicants']}),
{src[-1]['source']} the fewest ({src[-1]['hire_per_100_applicants']}). This follows directly from the simulation's
assumed pass rates. *(f32_by_source_SIMULATED)*
"""
    (ROOT / "docs" / "findings.md").write_text(t)
    print(t)


if __name__ == "__main__":
    main()

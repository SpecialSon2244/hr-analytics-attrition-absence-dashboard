"""Static PNG charts for the README (matplotlib), from docs/findings.json.

IBM charts use fictional IBM data; absence charts use the real UCI records;
hiring charts are SIMULATED and say so in the title.
"""
import json
import pathlib

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt  # noqa: E402

ROOT = pathlib.Path(__file__).resolve().parents[1]
IMG = ROOT / "images"
F = json.loads((ROOT / "docs" / "findings.json").read_text())

NAVY, TEAL, ORANGE, GREY, RED = "#1F3A5F", "#2A9D8F", "#E76F51", "#9AA5B1", "#C0392B"
plt.rcParams.update({"font.family": "DejaVu Sans", "font.size": 10, "axes.spines.top": False,
                     "axes.spines.right": False, "axes.titleweight": "bold", "axes.titlesize": 12,
                     "axes.titlelocation": "left", "figure.dpi": 150})
IBM_NOTE = "Data: IBM HR Analytics Employee Attrition & Performance (fictional dataset created by IBM data scientists), 1,470 employees."
UCI_NOTE = "Data: UCI Absenteeism at work (id 445), courier company in Brazil, Jul 2007 to Jul 2010, 740 records, 36 employees. CC BY 4.0."
SIM_NOTE = "SIMULATED data: seeded recruiting pipeline generated by src/simulate_hiring.py. Not real recruiting records."


def save(fig, name, note):
    fig.text(0.01, 0.01, note, fontsize=7, color="#555555")
    fig.tight_layout(rect=(0, 0.04, 1, 1))
    fig.savefig(IMG / name, facecolor="white")
    plt.close(fig)
    print(IMG / name)


def hbar(ax, labels, values, avg=None, fmt="{:.1f}%", colors=None):
    y = range(len(labels))
    ax.barh(list(y), values, color=colors or NAVY, height=0.65)
    ax.set_yticks(list(y), labels)
    ax.invert_yaxis()
    for i, v in enumerate(values):
        ax.text(v + max(values) * 0.01, i, fmt.format(v), va="center", fontsize=9)
    if avg is not None:
        ax.axvline(avg, color=ORANGE, ls="--", lw=1)
        ax.text(avg, -0.55, f" company avg {avg}%", color=ORANGE, fontsize=8, va="bottom")
    ax.set_xlim(0, max(values) * 1.18)


def overview():
    w, a, h = F["f1_workforce_overall"][0], F["f20_absence_overall"][0], F["f30_hiring_overall_SIMULATED"][0]
    tiles = [
        ("Headcount (IBM)", f"{w['employees']:,}", f"{w['active']:,} active, {w['leavers']} leavers"),
        ("Attrition rate (IBM)", f"{w['attrition_pct']}%", "leavers / headcount"),
        ("Avg tenure (IBM)", f"{w['avg_tenure_years']} yrs", f"leavers {w['avg_tenure_leavers']} yrs"),
        ("Absence hours (UCI)", f"{a['total_hours']:,}", f"{a['employees']} employees, {a['records']} records"),
        ("Hours per employee/yr (UCI)", f"{a['hours_per_employee_per_year']}", "3-year file, /3"),
        ("Median time to hire", f"{h['median_time_to_hire_days']:.0f} days", "SIMULATED pipeline"),
        ("Offer acceptance", f"{h['offer_accept_pct']}%", "SIMULATED pipeline"),
    ]
    fig, axes = plt.subplots(1, len(tiles), figsize=(14, 2.3))
    for ax, (t, v, s) in zip(axes, tiles):
        ax.axis("off")
        sim = "SIMULATED" in s
        ax.add_patch(plt.Rectangle((0, 0), 1, 1, transform=ax.transAxes, color="#F2F5F8" if not sim else "#FFF4E5"))
        ax.text(0.5, 0.75, t, ha="center", fontsize=9, color="#333333", transform=ax.transAxes)
        ax.text(0.5, 0.42, v, ha="center", fontsize=18, fontweight="bold", color=NAVY, transform=ax.transAxes)
        ax.text(0.5, 0.15, s, ha="center", fontsize=8, color=ORANGE if sim else "#555555", transform=ax.transAxes)
    fig.suptitle("HR Analytics: Attrition, Absence & Time to Hire (three separate datasets)", x=0.01, ha="left",
                 fontweight="bold")
    save(fig, "00_kpi_overview.png", "IBM = fictional IBM dataset. UCI = real absence records, different company. "
         "Hiring = SIMULATED.")


def attrition_by_role():
    rows = F["f4_by_job_role"]
    avg = F["f1_workforce_overall"][0]["attrition_pct"]
    fig, ax = plt.subplots(figsize=(9, 4.8))
    vals = [r["attrition_pct"] for r in rows]
    hbar(ax, [f"{r['job_role']} ({r['leavers']}/{r['employees']})" for r in rows], vals, avg,
         colors=[RED if v > 2 * avg else NAVY for v in vals])
    ax.set_title(f"Sales Representatives leave at {rows[0]['attrition_pct']}%, the highest of any role")
    ax.set_xlabel("Attrition rate (% of headcount who left)")
    save(fig, "01_attrition_by_role.png", IBM_NOTE)


def drivers():
    panels = [("f3_by_overtime", "overtime", "Overtime"), ("f5_by_tenure_band", "tenure_band", "Years at company"),
              ("f6_by_income_band", "income_band", "Monthly income"), ("f7_by_travel", "business_travel", "Business travel")]
    avg = F["f1_workforce_overall"][0]["attrition_pct"]
    fig, axes = plt.subplots(2, 2, figsize=(11, 6.5))
    for ax, (key, col, title) in zip(axes.flat, panels):
        rows = F[key]
        if key == "f7_by_travel":
            rows = sorted(rows, key=lambda r: r["attrition_pct"])
        labels = [str(r[col]).split(". ", 1)[-1] for r in rows]
        hbar(ax, labels, [r["attrition_pct"] for r in rows], avg)
        ax.set_title(title)
    ot = {r["overtime"]: r["attrition_pct"] for r in F["f3_by_overtime"]}
    fig.suptitle(f"Attrition by group: overtime workers leave at {ot['Yes']}% vs {ot['No']}%", x=0.01, ha="left",
                 fontweight="bold", fontsize=13)
    save(fig, "02_attrition_drivers.png", IBM_NOTE)


def overtime_income():
    rows = F["f10_overtime_x_income"]
    bands = [r["income_band"] for r in rows if r["overtime"] == "No"]
    fig, ax = plt.subplots(figsize=(9, 4.5))
    x = range(len(bands))
    for off, ot, c in [(-0.2, "No", TEAL), (0.2, "Yes", RED)]:
        v = [next(r["attrition_pct"] for r in rows if r["overtime"] == ot and r["income_band"] == b) for b in bands]
        ax.bar([i + off for i in x], v, width=0.4, color=c, label=f"Overtime: {ot}")
        for i, val in enumerate(v):
            ax.text(i + off, val + 0.8, f"{val}%", ha="center", fontsize=9)
    ax.set_xticks(list(x), [b.split(". ", 1)[1] + " / month" for b in bands])
    ax.set_ylabel("Attrition rate (%)")
    top = next(r for r in rows if r["overtime"] == "Yes" and r["income_band"] == bands[0])
    ax.set_title(f"Low pay plus overtime: {top['attrition_pct']}% left ({top['leavers']} of {top['employees']})")
    ax.legend(frameon=False)
    save(fig, "03_overtime_x_income.png", IBM_NOTE)


def absence_reason():
    rows = [r for r in F["f21_absence_by_reason"] if r["hours"] > 0][:10]
    fig, ax = plt.subplots(figsize=(9, 4.8))
    hbar(ax, [r["reason_name"] for r in rows], [r["pct_of_hours"] for r in rows],
         colors=[NAVY if r["reason_group"] == "ICD disease" else TEAL for r in rows])
    total = F["f20_absence_overall"][0]["total_hours"]
    ax.set_title(f"Musculoskeletal problems and injuries: {100 * (rows[0]['hours'] + rows[1]['hours']) / total:.1f}% "
                 "of absence hours")
    ax.set_xlabel("Share of all absence hours (%). Navy = ICD disease chapter, teal = other reason")
    save(fig, "04_absence_by_reason.png", UCI_NOTE)


def absence_weekday():
    rows = F["f22_absence_by_weekday"]
    fig, ax = plt.subplots(figsize=(8, 4))
    v = [r["hours"] for r in rows]
    ax.bar([r["weekday_name"] for r in rows], v, color=[RED if r["iso_weekday"] == 1 else NAVY for r in rows])
    for i, r in enumerate(rows):
        ax.text(i, r["hours"] + 20, f"{r['hours']:,} h\n{r['pct_of_hours']}%", ha="center", fontsize=9)
    ax.set_ylim(0, max(v) * 1.2)
    ax.set_ylabel("Absence hours")
    ax.set_title(f"Mondays carry {rows[0]['pct_of_hours']}% of absence hours, Thursdays {rows[3]['pct_of_hours']}%")
    save(fig, "05_absence_by_weekday.png", UCI_NOTE)


def funnel():
    rows = F["f31_funnel_SIMULATED"]
    fig, ax = plt.subplots(figsize=(9, 4.2))
    vals = [r["candidates"] for r in rows]
    y = range(len(rows))
    ax.barh(list(y), vals, color=ORANGE, height=0.65)
    ax.set_yticks(list(y), [r["stage"].split(". ", 1)[1] for r in rows])
    ax.invert_yaxis()
    for i, r in enumerate(rows):
        ax.text(r["candidates"] + 120, i, f"{r['candidates']:,}  ({r['pct_of_applicants']:.1f}% of applicants)",
                va="center", fontsize=9)
    ax.set_xlim(0, max(vals) * 1.45)
    ax.set_title(f"SIMULATED recruiting funnel: {rows[0]['candidates']:,} applicants, {rows[-1]['candidates']:,} hires")
    save(fig, "06_hiring_funnel_SIMULATED.png", SIM_NOTE)


def time_to_hire():
    rows = F["f34_hires_by_quarter_SIMULATED"]
    fig, ax = plt.subplots(figsize=(9, 4.2))
    q = [r["quarter_filled"] for r in rows]
    ax.bar(q, [r["hires"] for r in rows], color="#F4C095", label="Hires (left axis)")
    ax.set_ylabel("Hires")
    ax2 = ax.twinx()
    ax2.plot(q, [r["median_time_to_hire_days"] for r in rows], color=ORANGE, marker="o", label="Median time to hire")
    ax2.plot(q, [r["median_time_to_fill_days"] for r in rows], color=NAVY, marker="s", label="Median time to fill")
    ax2.set_ylim(0, 50)
    ax2.set_ylabel("Days")
    ax2.spines["right"].set_visible(True)
    h = F["f30_hiring_overall_SIMULATED"][0]
    ax.set_title(f"SIMULATED: median time to hire {h['median_time_to_hire_days']:.0f} days, "
                 f"time to fill {h['median_time_to_fill_days']:.0f} days")
    h1, l1 = ax.get_legend_handles_labels()
    h2, l2 = ax2.get_legend_handles_labels()
    ax.legend(h1 + h2, l1 + l2, loc="upper left", ncol=3, frameon=False, fontsize=8)
    ax.set_ylim(0, max(r["hires"] for r in rows) * 1.35)
    save(fig, "07_time_to_hire_SIMULATED.png", SIM_NOTE + " 2026-Q3 is partial (snapshot 30 Sep 2026).")


if __name__ == "__main__":
    IMG.mkdir(exist_ok=True)
    for fn in [overview, attrition_by_role, drivers, overtime_income, absence_reason, absence_weekday, funnel,
               time_to_hire]:
        fn()

"""Run every named query in sql/findings.sql and write docs/findings_results.md
and docs/findings.json (the numbers quoted in README.md and docs/findings.md)."""
import json
import pathlib
import re

import duckdb

ROOT = pathlib.Path(__file__).resolve().parents[1]


def queries() -> dict[str, str]:
    text = (ROOT / "sql" / "findings.sql").read_text()
    out = {}
    for block in re.split(r"^-- name: ", text, flags=re.M)[1:]:
        head, sql = block.split("\n", 1)
        out[head.strip()] = sql.strip().rstrip(";")
    return out


def named_query(name: str) -> str:
    return queries()[name]


def fmt(v):
    if isinstance(v, float):
        return f"{v:,.2f}".rstrip("0").rstrip(".") if v != int(v) else f"{int(v):,}"
    if isinstance(v, int) and not isinstance(v, bool):
        return f"{v:,}"
    return str(v)


def main() -> None:
    con = duckdb.connect(str(ROOT / "data" / "hr.duckdb"), read_only=True)
    md = ["# Findings results (generated by src/findings.py, do not edit)", "",
          "IBM tables are fictional data; `_SIMULATED` sections come from the simulated recruiting pipeline.", ""]
    js = {}
    for name, sql in queries().items():
        rel = con.sql(sql)
        cols, rows = rel.columns, rel.fetchall()
        rows = [[float(v) if hasattr(v, "is_finite") else v for v in r] for r in rows]
        js[name] = [dict(zip(cols, r)) for r in rows]
        md += [f"## {name}", "", "| " + " | ".join(cols) + " |", "|" + "---|" * len(cols)]
        md += ["| " + " | ".join(fmt(v) for v in r) + " |" for r in rows]
        md.append("")
    (ROOT / "docs" / "findings_results.md").write_text("\n".join(md))
    (ROOT / "docs" / "findings.json").write_text(json.dumps(js, indent=1, default=str))
    print("\n".join(md))


if __name__ == "__main__":
    main()
